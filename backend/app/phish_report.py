"""Turns a stored phishing analysis into a report: Markdown (plain) and PDF (ReportLab, pure Python, no browser needed).

Everything in the report comes from the rule-based analysis. No AI model decides or writes the verdict, evidence or indicators.
"""
import datetime as dt
import io
from xml.sax.saxutils import escape

VERDICT_TEXT = {
    "PHISHING": "Phishing: very likely a malicious message",
    "SUSPICIOUS": "Suspicious: could not be verified as safe",
    "SAFE": "No strong phishing signs found",
}
AI_AGREE = {"agree": "agrees with", "partly": "partly agrees with", "disagree": "disagrees with"}
SUMMARY = {
    "PHISHING": "Several independent checks agree that this message is designed to trick the recipient. Treat it as an attack.",
    "SUSPICIOUS": "Some checks raised concerns but the evidence is not conclusive. Verify it before acting on it.",
    "SAFE": "The checks found no strong signs of phishing. This is not a guarantee: targeted attacks can look clean.",
}


def _fmt_time(value) -> str:
    return value.strftime("%Y-%m-%d %H:%M UTC") if isinstance(value, dt.datetime) else str(value or "")


def summary_line(rec: dict) -> str:
    return SUMMARY.get(rec["verdict"], "")


# ---------------------------------------------------------------------------------------------- Markdown
def build_markdown(rec: dict) -> str:
    r = rec["result"]
    e = r["email"]
    L = [f"# Phishing analysis report #{rec['id']}", "",
         f"**Verdict:** {r['verdict']}  ·  **Risk score:** {r['score']} (suspicious from {r['thresholds']['suspicious']}, phishing from {r['thresholds']['phishing']})",
         f"**Analysed:** {_fmt_time(rec['created_at'])}  ·  **Source:** {rec['source']}", "", f"> {VERDICT_TEXT[r['verdict']]}. {summary_line(rec)}", "",
         "## The message", "", f"- **From:** {e['from_name']} <{e['from_addr']}>", f"- **Reply-To:** {e['reply_to'] or '(none)'}", f"- **Subject:** {e['subject']}",
         f"- **Date:** {e['date']}", f"- **SHA-256:** `{e['raw_sha256']}`", "", "## Why this verdict", ""]
    L += [f"- **+{x['points']:g}** {x['text']}" + (f"  \n  _Evidence:_ {x['evidence']}" if x["evidence"] else "") for x in r["reasons"]] or ["- No warning signs found."]
    if r["positives"]:
        L += ["", "**Good signs:**"] + [f"- {p}" for p in r["positives"]]
    ai = r.get("ai")
    if ai and ai.get("available"):
        L += ["", f"## AI analyst assessment ({ai['model']} on Groq)", "",
              f"**AI verdict:** {ai['verdict']} (confidence {ai['confidence']}%)  ·  it {AI_AGREE[ai['agreement']]} the rule-based verdict", "", ai["summary"], ""]
        L += [f"- {x}" for x in ai["reasons"]]
        if ai["extra_signals"]:
            L += ["", "**Signals the rules did not report:**"] + [f"- {x}" for x in ai["extra_signals"]]
        L += ["", "_The AI opinion is advisory. The official verdict above comes from the rule-based checks._"]
    L += ["", "## Indicators to block or hunt for", ""]
    ind = r["indicators"]
    for title, items in (("Domains", ind["domains"]), ("URLs", ind["urls"]), ("IP addresses", ind["ips"]), ("Sender addresses", ind["emails"])):
        if items:
            L += [f"**{title}**", ""] + [f"- `{i}`" for i in items] + [""]
    if ind["file_hashes"]:
        L += ["**Attachments (SHA-256)**", ""] + [f"- `{h['name']}`: `{h['sha256']}`" for h in ind["file_hashes"]] + [""]
    L += ["## MITRE ATT&CK mapping", ""] + ([f"- **{a['id']}** {a['name']}" for a in r["attack"]] or ["- None identified."])
    L += ["", "## Recommended actions", ""] + [f"{i}. {a}" for i, a in enumerate(r["actions"], 1)]
    L += ["", "---", "_Generated by CYBERMIND AI. Rule-based analysis; verify important decisions with a human analyst._", ""]
    return "\n".join(L)


# ---------------------------------------------------------------------------------------------- PDF
def _latin(s: str) -> str:
    return (s or "").encode("latin-1", "replace").decode("latin-1")


def build_pdf(rec: dict) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    r = rec["result"]
    e = r["email"]
    BG, INK, DIM, LINE = colors.HexColor("#06070c"), colors.HexColor("#e6e9ff"), colors.HexColor("#9aa1cc"), colors.HexColor("#2a2f55")
    ACC = colors.HexColor("#8f8bff")
    TIER = {"PHISHING": colors.HexColor("#ff4d73"), "SUSPICIOUS": colors.HexColor("#ffb547"), "SAFE": colors.HexColor("#34f5c5")}[r["verdict"]]

    body = ParagraphStyle("body", fontName="Helvetica", fontSize=9.4, leading=13.4, textColor=INK, spaceAfter=3)
    small = ParagraphStyle("small", parent=body, fontSize=8.2, leading=11.4, textColor=DIM)
    mono = ParagraphStyle("mono", parent=body, fontName="Courier", fontSize=8, leading=10.5)
    h2 = ParagraphStyle("h2", parent=body, fontName="Helvetica-Bold", fontSize=11.5, leading=15, textColor=ACC, spaceBefore=10, spaceAfter=4)
    title = ParagraphStyle("title", parent=body, fontName="Helvetica-Bold", fontSize=19, leading=23, textColor=colors.white)
    banner = ParagraphStyle("banner", parent=body, fontName="Helvetica-Bold", fontSize=14, leading=18, textColor=colors.white)

    def P(t, st=body):
        return Paragraph(escape(_latin(str(t))), st)

    def table(rows, widths, head=None):
        data = ([[P(h, ParagraphStyle("th", parent=small, fontName="Helvetica-Bold", textColor=ACC)) for h in head]] if head else []) + rows
        t = Table(data, colWidths=[w * mm for w in widths], repeatRows=1 if head else 0)
        t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE),
                               ("LEFTPADDING", (0, 0), (-1, -1), 4), ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                               ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]))
        return t

    story = [P("CYBERMIND AI", ParagraphStyle("k", parent=small, fontName="Helvetica-Bold", textColor=ACC)),
             P(f"Phishing analysis report #{rec['id']}", title), Spacer(1, 4)]
    bt = Table([[P(VERDICT_TEXT[r["verdict"]], banner), P(f"RISK {r['score']:g}", ParagraphStyle("sc", parent=banner, alignment=2))]], colWidths=[125 * mm, 45 * mm])
    bt.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#14172e")), ("LINEBEFORE", (0, 0), (0, -1), 4, TIER),
                            ("LEFTPADDING", (0, 0), (-1, -1), 10), ("TOPPADDING", (0, 0), (-1, -1), 8), ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                            ("VALIGN", (0, 0), (-1, -1), "MIDDLE")]))
    story += [bt, Spacer(1, 4), P(summary_line(rec)),
              P(f"Analysed {_fmt_time(rec['created_at'])}  |  source: {rec['source']}  |  thresholds: suspicious from {r['thresholds']['suspicious']:g}, phishing from {r['thresholds']['phishing']:g}", small)]

    story += [P("The message", h2), table([[P("From", small), P(f"{e['from_name']} <{e['from_addr']}>")], [P("Reply-To", small), P(e["reply_to"] or "(none)")],
                                           [P("Subject", small), P(e["subject"])], [P("Date", small), P(e["date"])],
                                           [P("SHA-256", small), P(e["raw_sha256"], mono)]], [24, 146])]

    story.append(P("Why this verdict", h2))
    rows = [[P(f"+{x['points']:g}", ParagraphStyle("pt", parent=body, fontName="Helvetica-Bold", textColor=TIER)),
             [P(x["text"]), P(x["evidence"], small)] if x["evidence"] else P(x["text"])] for x in r["reasons"]]
    story.append(table(rows, [14, 156]) if rows else P("No warning signs found."))
    for g in r["positives"]:
        story.append(P("+ " + g, ParagraphStyle("g", parent=body, textColor=colors.HexColor("#34f5c5"))))

    ai = r.get("ai")
    if ai and ai.get("available"):
        story.append(P(f"AI analyst assessment ({ai['model']} on Groq)", h2))
        story.append(P(f"AI verdict: {ai['verdict']} (confidence {ai['confidence']}%). It {AI_AGREE[ai['agreement']]} the rule-based verdict.",
                       ParagraphStyle("aiv", parent=body, fontName="Helvetica-Bold")))
        story.append(P(ai["summary"]))
        for x in ai["reasons"]:
            story.append(P("- " + x))
        if ai["extra_signals"]:
            story.append(P("Signals the rules did not report: " + "; ".join(ai["extra_signals"]), small))
        story.append(P("The AI opinion is advisory. The official verdict comes from the rule-based checks.", small))

    ind = r["indicators"]
    story.append(P("Indicators to block or hunt for", h2))
    blocks = []
    for ttl, items in (("Domains", ind["domains"]), ("URLs", ind["urls"]), ("IP addresses", ind["ips"]), ("Sender addresses", ind["emails"])):
        if items:
            blocks.append([P(ttl, small), [P(i, mono) for i in items[:15]]])
    for h in ind["file_hashes"]:
        blocks.append([P("Attachment", small), [P(h["name"]), P(h["sha256"], mono)]])
    story.append(table(blocks, [28, 142]) if blocks else P("None extracted."))

    story.append(KeepTogether([P("MITRE ATT&CK mapping", h2)] + ([P(f"{a['id']}  {a['name']}") for a in r["attack"]] or [P("None identified.")])))
    story.append(KeepTogether([P("Recommended actions", h2)] + [P(f"{i}. {a}") for i, a in enumerate(r["actions"], 1)]))
    story += [Spacer(1, 10), P("Generated by CYBERMIND AI. The analysis is rule-based and explainable; confirm important decisions with a human analyst.", small)]

    def page(canvas, doc):
        canvas.saveState()
        canvas.setFillColor(BG)
        canvas.rect(0, 0, A4[0], A4[1], stroke=0, fill=1)
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(DIM)
        canvas.drawString(20 * mm, 10 * mm, "CYBERMIND AI  -  Phishing analysis")
        canvas.drawRightString(190 * mm, 10 * mm, f"Page {doc.page}")
        canvas.restoreState()

    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=16 * mm, bottomMargin=18 * mm,
                      title=f"Phishing analysis report #{rec['id']}", author="CYBERMIND AI").build(story, onFirstPage=page, onLaterPages=page)
    return buf.getvalue()
